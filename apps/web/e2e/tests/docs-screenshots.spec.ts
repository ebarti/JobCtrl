async function publishStagedScreenshots(): Promise<void> {
  if (!stagedScreenshotsDir) {
    throw new Error("Documentation screenshot staging is not initialized.");
  }
  const expectedNames = [...desktopSurfaces, ...mobileSurfaces]
    .map((surface) => surface.name)
    .sort();
  const actualNames = (await fs.readdir(stagedScreenshotsDir))
    .filter((name) => name.endsWith(".png"))
    .sort();
  expect(actualNames).toEqual(expectedNames);

  const stagedDir = stagedScreenshotsDir;
  const backupDir = `${screenshotsDir}.backup-${process.pid}`;
  const nextHeroPath = `${publicHeroScreenshotPath}.next-${process.pid}`;
  await fs.rm(backupDir, { recursive: true, force: true });
  await fs.rm(nextHeroPath, { force: true });
  await fs.copyFile(path.join(stagedDir, heroScreenshotName), nextHeroPath);

  let previousGalleryMoved = false;
  let stagedGalleryPublished = false;
  try {
    try {
      await fs.rename(screenshotsDir, backupDir);
      previousGalleryMoved = true;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }

    await fs.rename(stagedDir, screenshotsDir);
    stagedScreenshotsDir = null;
    stagedGalleryPublished = true;
    await fs.rename(nextHeroPath, publicHeroScreenshotPath);
  } catch (error) {
    if (stagedGalleryPublished) {
      await fs.rename(screenshotsDir, stagedDir);
      stagedScreenshotsDir = stagedDir;
    }
    if (previousGalleryMoved) {
      await fs.rename(backupDir, screenshotsDir);
    }
    await fs.rm(nextHeroPath, { force: true });
    throw error;
  }

  if (previousGalleryMoved) {
    await fs.rm(backupDir, { recursive: true, force: true });
  }
}

async function nonJobActivityDetailPath(page: Page): Promise<string> {
  const response = await page.request.get(
    "/v1/debug/activity?page=1&pageSize=200&sort=occurred_at&dir=desc",
  );
  if (!response.ok()) {
    throw new Error(
      `Unable to load synthetic activity events (${response.status()}).`,
    );
  }
  const payload = (await response.json()) as {
    items?: Array<{ eventId?: string; jobKey?: string | null }>;
  };
  const event = payload.items?.find(
    (candidate) => !candidate.jobKey && candidate.eventId,
  );
  if (!event?.eventId) {
    throw new Error(
      "Synthetic screenshot seed must expose a non-job activity event.",
    );
  }

  // Local routes redirect job-linked events back to their owning job. Capture a
  // workflow event instead so this is a genuine direct Activity Detail route;
  // the demo-only direct-load feature flag is not enabled in the local E2E app.
  return `/activity/${encodeURIComponent(event.eventId)}`;
}

