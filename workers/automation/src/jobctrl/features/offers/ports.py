"""Narrow contracts for the Offers ledger and its transaction participants."""

from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Any, Protocol


class OfferJobsPort(Protocol):
    def get_posting_snapshot(self, job_id: str, connection: Any = None) -> dict: ...


class OfferApplicationsPort(Protocol):
    def ensure_offer_milestone(self, job_id: str, connection: Any = None) -> dict: ...


class OfferEventsPort(Protocol):
    def append(self, connection: Any, event_type: str, payload: dict, *,
               feature: str, aggregate_id: str | None = None) -> int: ...


class OfferTransaction(Protocol):
    """Offer operations that must commit or roll back as one unit."""

    def read_offer(self, job_id: str) -> dict: ...
    def append_terms(self, job_id: str, revision: dict) -> None: ...
    def append_decision(self, job_id: str, decision: dict) -> None: ...
    def ensure_offer_milestone(self, job_id: str) -> None: ...
    def publish_change(self, job_id: str, revision_id: str, decision_id: str | None) -> None: ...


class OfferRepository(Protocol):
    def read_offer(self, job_id: str, connection: Any = None) -> dict: ...
    def transaction(self) -> AbstractContextManager[OfferTransaction]: ...
    def delete_job_data(self, job_id: str, connection: Any = None) -> None: ...
