"""Only the public posting, model and requirement-store seams cross I/O."""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, Protocol

from pydantic import BaseModel

from .domain import ModelCallBudget


class PostingReader(Protocol):
    def get_posting_snapshot(self, job_id: str, connection: Any = None) -> dict: ...
    def get_job_snapshots(self, job_ids: list[str], connection: Any = None, *, include_deleted: bool = False) -> dict: ...
    def assert_posting_current(
        self, job_id: str, revision: int, source_hash: str | None = None, connection: Any = None
    ) -> dict: ...


class RequirementModel(Protocol):
    async def determine(
        self, *, kind: str, schema: type[BaseModel], prompt_version: str,
        instruction: str, sources: list[dict], context: dict, entity_id: str,
        validate: Callable[[Any], None],
        budget: ModelCallBudget | None = None,
    ) -> tuple[Any, dict]: ...


class RequirementStore(Protocol):
    def read_session(self) -> Any: ...
    def current_snapshot(self, job_id: str, connection: Any = None) -> dict | None: ...
    def job_bindings(self, job_ids: list[str], connection: Any) -> dict: ...
    def assert_snapshot_current(self, snapshot: dict, connection: Any) -> None: ...
    def get_meaning(self, requirement_id: str, revision: int | None = None, connection: Any = None) -> dict: ...
    def catalog(self, *, limit: int, offset: int, query: str) -> dict: ...
    def index_status(self) -> dict: ...
    def rebuild_index(self, expected_catalog_revision: int) -> dict: ...
    def occurrences(self, requirement_id: str, *, limit: int, offset: int, connection: Any = None) -> list[dict]: ...
    def latest_attempt(self, job_id: str, connection: Any = None) -> dict | None: ...
    def delete_job_data(self, job_id: str, connection: Any = None) -> None: ...
    def catalog_snapshot(self, query: str) -> tuple[int, list[dict]]: ...
    def retrieval_ids(self, query: str, catalog_revision: int) -> list[str]: ...
    def model_call(self, input_fingerprint: str) -> dict | None: ...
    def save_model_call(
        self, *, input_fingerprint: str, operation: str, posting: dict, catalog_revision: int | None,
        result: dict, provenance: dict, posting_guard: Callable,
    ) -> dict: ...
    def start_attempt(self, attempt: dict) -> None: ...
    def accepted_action(self, attempt_id: str, input_fingerprint: str) -> dict | None: ...
    def accepted_revision_action(self, operation_id: str, input_fingerprint: str) -> dict | None: ...
    def finish_attempt(self, attempt_id: str, state: str, failure_code: str | None = None) -> None: ...
    def revise_meaning(
        self, *, revised: dict, expected_revision: int, catalog_revision: int,
        posting: dict, posting_guard: Callable, cancelled: Callable[[], bool],
        operation_id: str | None = None, input_fingerprint: str | None = None,
    ) -> dict: ...
    def publish(
        self, *, posting: dict, expected_revision: int, catalog_revision: int,
        meanings: list[dict], occurrences: list[dict], extraction_id: str,
        attempt_id: str, posting_guard: Callable, cancelled: Callable[[], bool], event_type: str = "RequirementsUpdated",
    ) -> dict: ...
