"""Only the public posting, model and requirement-store seams cross I/O."""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, Protocol

from pydantic import BaseModel

from .domain import ModelCallBudget


class PostingReader(Protocol):
    def get_posting_snapshot(self, job_id: str, connection: Any = None) -> dict: ...
    def posting_text_at_revision(self, job_id: str, revision: int, connection: Any) -> str | None: ...
    def get_job_snapshots(self, job_ids: list[str], connection: Any = None, *, include_deleted: bool = False) -> dict: ...
    def assert_posting_current(
        self, job_id: str, revision: int, source_hash: str | None = None, connection: Any = None
    ) -> dict: ...


class RequirementModel(Protocol):
    def refused_extraction_receipt(self, attempt_id: str, source_id: str, code: str, connection: Any) -> str | None: ...
    def coordinate_work(self, keys, cancelled): ...
    def share_receipt(self, keys): ...
    def receipt(self, receipt_id: str) -> dict: ...
    async def determine(
        self, *, kind: str, schema: type[BaseModel], prompt_version: str,
        instruction: str, sources: list[dict], context: dict, entity_id: str | None,
        validate: Callable[[Any], None],
        budget: ModelCallBudget | None = None,
        publication_posting: dict | None = None, source_binding: dict | None = None,
        catalog_guard: Callable | None = None,
        retained_request: dict | None = None, pin_request: Callable | None = None,
        refused_receipt_id: str | None = None, pin_refusal: Callable[[str], None] | None = None,
    ) -> tuple[Any, dict]: ...


class RequirementStore(Protocol):
    def admit_catalog_prompt(self, operation_id: str, prompt_version: str, connection: Any) -> None: ...
    def catalog_prompt(self, operation_id: str) -> str | None: ...
    def admit_consolidation_prompt(self, operation_id: str, current: str, predecessor: str) -> str: ...
    def aliases(self, connection: Any = None) -> dict: ...
    def alias_root(self, requirement_id: str, connection: Any = None) -> str: ...
    def normalization_capture(self, connection: Any = None) -> dict: ...
    def assert_normalization_capture(self, captured: dict, connection: Any) -> None: ...
    def normalization_certificate(self, connection: Any = None) -> dict | None: ...
    def normalization_action(self, operation_id: str, input_fingerprint: str) -> dict | None: ...
    def normalization_model_call(self, input_fingerprint: str) -> dict | None: ...
    def reserve_normalization_call(self, operation_id: str, input_fingerprint: str, guard: Callable, *, connection: Any) -> int: ...
    def assert_normalization_call_available(self, operation_id: str, input_fingerprint: str, connection: Any = None) -> None: ...
    def save_normalization_model_call(self, *, input_fingerprint: str, operation: str,
                                     catalog_revision: int, result: dict, provenance: dict, guard: Callable) -> dict: ...
    def publish_normalization(self, **kwargs: Any) -> dict: ...
    def publish_empty_snapshot(self, **kwargs: Any) -> dict: ...
    def read_session(self) -> Any: ...
    def current_snapshot(self, job_id: str, connection: Any = None) -> dict | None: ...
    def job_bindings(self, job_ids: list[str], connection: Any, *, scored=None) -> dict: ...
    def assert_snapshot_current(self, snapshot: dict, connection: Any) -> None: ...
    def get_meaning(self, requirement_id: str, revision: int | None = None, connection: Any = None) -> dict: ...
    def accepted_occurrence_jobs(self, connection: Any, requirement_id: str | None = None) -> list[tuple[str, str]]: ...
    def index_status(self) -> dict: ...
    def rebuild_index(self, expected_catalog_revision: int) -> dict: ...
    def occurrences(self, requirement_id: str, *, limit: int, offset: int, connection: Any = None) -> list[dict]: ...
    def history(self, requirement_id: str, *, kind: str, limit: int, offset: int, connection: Any) -> dict: ...
    def latest_attempt(self, job_id: str, connection: Any = None) -> dict | None: ...
    def attempt_fingerprint(self, attempt_id: str) -> str | None: ...
    def delete_job_data(self, job_id: str, connection: Any = None) -> None: ...
    def orphaned_meaning_ids_for_job(self, job_id: str, connection: Any) -> list[str]: ...
    def delete_meanings(self, requirement_ids: list[str], job_id: str, connection: Any) -> None: ...
    def catalog_snapshot(self, connection: Any = None) -> tuple[int, list[dict]]: ...
    def model_call(self, input_fingerprint: str) -> dict | None: ...
    def save_model_call(
        self, *, input_fingerprint: str, operation: str, posting: dict, catalog_revision: int | None,
        result: dict, provenance: dict, posting_guard: Callable,
    ) -> dict: ...
    def reserve_correction_call(self, attempt_id: str, input_fingerprint: str, maximum: int,
                                posting: dict, posting_guard: Callable, *, connection: Any) -> int: ...
    def check_correction_call(self, attempt_id: str, input_fingerprint: str, maximum: int,
                              connection: Any = None) -> tuple[str, str, int]: ...
    def start_attempt(self, attempt: dict) -> None: ...
    def record_cohort_attempts(self, job_operations: list[tuple[str, str]], state: str,
                              failure_code: str | None, connection: Any) -> None: ...
    def accepted_action(self, attempt_id: str, input_fingerprint: str) -> dict | None: ...
    def accepted_revision_action(self, operation_id: str, input_fingerprint: str) -> dict | None: ...
    def finish_attempt(self, attempt_id: str, state: str, failure_code: str | None = None, *, details: dict | None = None) -> None: ...
    def revise_meaning(
        self, *, revised: dict, expected_revision: int, catalog_revision: int,
        posting: dict, posting_guard: Callable, cancelled: Callable[[], bool],
        operation_id: str | None = None, input_fingerprint: str | None = None,
    ) -> dict: ...
    def publish(
        self, *, posting: dict, expected_revision: int, catalog_revision: int,
        meanings: list[dict], occurrences: list[dict], extraction_id: str,
        attempt_id: str, posting_guard: Callable, cancelled: Callable[[], bool], extraction: dict,
        event_type: str = "RequirementsUpdated",
        previous_snapshot: dict | None = None,
    ) -> dict: ...
