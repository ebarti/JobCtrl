"""Compensation's application-facing persistence and public-owner ports."""

from __future__ import annotations

from collections.abc import Callable, Sequence
from typing import TYPE_CHECKING, Any, ContextManager, Literal, Protocol

from .core.ports import Classification, Model, Observation, PayJudgment, PriceLevel, Rate, Rates, Source

if TYPE_CHECKING:
    from .geography import CompanyIdentityDecision

RecordKind = Literal["posted", "market"]


class ModelDetermination(Protocol):
    @property
    def value(self) -> dict[str, Any]: ...

    @property
    def provenance(self) -> dict[str, Any]: ...


class CompensationModel(Model, Protocol):
    """Source-bound decisions and reconstruction from verified receipts."""

    async def company_identity(self, left: Observation, right: Observation) -> CompanyIdentityDecision: ...
    def rebuild_posted(self, source: Source, result: ModelDetermination) -> PayJudgment: ...
    def rebuild_classification(self, source: Source, result: ModelDetermination) -> Classification: ...
    def rebuild_company_identity(self, source: Source, result: ModelDetermination) -> CompanyIdentityDecision: ...


class OfficialDataAuthority(Protocol):
    """Revalidate recorded rate and price sources without acquiring data."""

    def verify_rate(self, value: dict) -> Rate: ...
    def rate_snapshot(self, value: dict) -> tuple[Rate, ...]: ...
    def price_snapshot(self, value: dict, year: int) -> tuple[PriceLevel, ...]: ...
    def verify_prices(
        self, source_data: dict, target_data: dict, source_country: str, target_country: str
    ) -> tuple[PriceLevel, PriceLevel]: ...


class ProviderTargetOutcome(Protocol):
    def as_dict(self) -> dict[str, Any]: ...


class ProviderLoadResult(Protocol):
    @property
    def observations(self) -> tuple[Observation, ...]: ...

    @property
    def errors(self) -> tuple[str, ...]: ...

    @property
    def levels_fyi_targets(self) -> tuple[ProviderTargetOutcome, ...]: ...

    @property
    def diagnostics(self) -> tuple[tuple[str, Any], ...]: ...


class CompensationProvider(Protocol):
    def load(self, target: Classification, policy: dict) -> ProviderLoadResult: ...


class CompensationSourceSet(Protocol):
    @property
    def providers(self) -> Sequence[tuple[str, CompensationProvider]]: ...

    @property
    def rates(self) -> Callable[[], Rates]: ...

    @property
    def price_levels(self) -> Callable[[int], tuple[PriceLevel, ...]]: ...


class CompensationSourceFactory(Protocol):
    def __call__(self, options: dict, run_id: str, preferences: dict) -> CompensationSourceSet: ...


class CompensationUnitOfWork(Protocol):
    """One consistent feature operation; no storage connection is exposed."""

    def posting(self, job_id: str, *, include_deleted: bool = False) -> dict: ...
    def assert_posting_current(self, snapshot: dict) -> None: ...
    def policy_snapshot(self) -> tuple[dict, int]: ...
    def set_policy(self, source_id: str, value: dict, expected_revision: int) -> int: ...
    def record(self, kind: RecordKind, job_id: str) -> dict | None: ...
    def completion(self, operation_id: str) -> dict | None: ...
    def refresh_state(self, job_id: str) -> dict | None: ...
    def claim(self, job_id: str, attempt: str, now: str, expiry: str) -> None: ...
    def renew(self, job_id: str, attempt: str, now: str, expiry: str) -> None: ...
    def require_owner(self, job_id: str, attempt: str, now: str) -> None: ...
    def save_record(self, kind: RecordKind, snapshot: dict, record: dict, attempt: str) -> None: ...
    def record_source_receipt(self, job_id: str, attempt: str, source_id: str, receipt: dict, now: str) -> None: ...
    def set_refresh_result(self, job_id: str, attempt: str, status: str, code: str | None, now: str) -> bool: ...
    def save_completion(self, operation_id: str, job_id: str, input_hash: str, outcome: dict) -> None: ...
    def source_receipts(self, job_id: str, attempt: str) -> list[dict]: ...
    def fresh_benchmark_inputs(self, occupation: str, seniority: str, component: str, now: str) -> list[dict]: ...
    def benchmark_acquisition(self, fact_ref: str, fetched_at: str) -> dict | None: ...
    def save_benchmark_input(self, fact: dict, fetched_at: str, fresh_until: str) -> None: ...
    def fresh_price_snapshots(self, reference_year: int, now: str) -> list[dict]: ...
    def price_acquisition(self, snapshot_ref: str, fetched_at: str) -> dict | None: ...
    def save_price_snapshot(self, source: dict, year: int, fetched_at: str, fresh_until: str) -> None: ...
    def fresh_rate_snapshots(self, now: str) -> list[dict]: ...
    def rate_acquisition(self, snapshot_ref: str, fetched_at: str) -> dict | None: ...
    def save_rate_snapshot(self, source: dict, fetched_at: str, fresh_until: str) -> None: ...
    def append_event(self, event_type: str, payload: dict, aggregate_id: str) -> None: ...
    def verified_model_result(self, source: Source, receipt_id: str, kind: str) -> ModelDetermination: ...
    def settings_snapshot(self) -> dict: ...
    def automatic_enabled(self) -> bool: ...
    def delete_job(self, job_id: str) -> None: ...


class CompensationStore(Protocol):
    def read(self, connection: Any = None) -> ContextManager[CompensationUnitOfWork]: ...
    def write(self, connection: Any = None) -> ContextManager[CompensationUnitOfWork]: ...
