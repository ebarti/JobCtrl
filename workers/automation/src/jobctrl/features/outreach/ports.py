"""Public snapshot readers and the real external model boundary."""

from __future__ import annotations

from typing import Any, ContextManager, Protocol


class OutreachSession(Protocol):
    connection: Any

    def thread(self, thread_id: str) -> dict | None: ...
    def for_contact(self, contact_id: str, job_id: str | None) -> dict | None: ...
    def threads(self) -> list[dict]: ...
    def put(self, thread: dict) -> None: ...
    def receipt(self, request_id: str) -> dict | None: ...
    def put_receipt(self, request_id: str, payload_hash: str, send_log: dict) -> None: ...
    def publication_receipt(self, request_id: str) -> dict | None: ...
    def put_publication_receipt(self, request_id: str, payload_hash: str, publication: dict) -> None: ...
    def determination(self, record: dict) -> None: ...
    def model_record(self, determination_id: str) -> dict | None: ...
    def event(self, name: str, aggregate_id: str, payload: dict) -> None: ...


class OutreachStore(Protocol):
    def read(self, connection: Any = None) -> ContextManager[OutreachSession]: ...
    def write(self) -> ContextManager[OutreachSession]: ...


class ContactsReader(Protocol):
    def snapshot(self, contact_id: str, connection: Any = None) -> dict: ...
    def assert_current(self, snapshot: dict, connection: Any = None) -> None: ...


class ProfileReader(Protocol):
    def snapshot(self, profile_id: str = "default", connection: Any = None) -> Any: ...
    def assert_current(self, snapshot: Any, connection: Any = None) -> None: ...


class JobsReader(Protocol):
    def get_posting_snapshot(self, job_id: str, connection: Any = None) -> dict: ...
    def assert_posting_current(self, job_id: str, revision: int, source_hash: str | None = None, connection: Any = None) -> None: ...


class OffersReader(Protocol):
    def current_terms(self, job_id: str, revision_id: str | None = None, connection: Any = None) -> dict: ...
    def assert_terms_current(self, context: dict, connection: Any = None) -> None: ...


class MessageModel(Protocol):
    async def determine(self, *, operation: str, instructions: str, sources: list[dict], response_schema: dict,
                        context: dict | None = None, prompt_version: str = "1", lane: str = "interactive",
                        model: str | None = None) -> Any: ...
    def receipt(self, receipt_id: str, connection: Any = None) -> dict: ...
    def fingerprint(self, *, operation: str, instructions: str, sources: list[dict], response_schema: dict,
                    context: dict | None = None, prompt_version: str = "1", lane: str = "interactive",
                    model: str | None = None, selection: dict | None = None) -> str: ...
