"""Application-owned ports at provider, canonical-owner and storage boundaries."""

from typing import Protocol


class DestinationPolicy(Protocol):
    async def is_public(self, url: str) -> bool: ...


class ExecutionPort(Protocol):
    def begin(self, lease: dict) -> None: ...
    def stop(self, lease: dict) -> None: ...
    async def run_board_unit(self, context, lease: dict, unit: dict, settings: dict, previous) -> None: ...
    async def run_registered_source(self, context, lease: dict, source: dict, settings: dict) -> bool: ...


class ModelResult(Protocol):
    @property
    def value(self) -> dict: ...
    @property
    def provenance(self) -> dict: ...


class ModelPort(Protocol):
    async def determine(
        self,
        *,
        operation: str,
        instructions: str,
        sources: list,
        response_schema: dict,
        context: dict | None = None,
        prompt_version: str = "1",
        lane: str = "interactive",
        model: str | None = None,
    ) -> ModelResult: ...


class JobsPort(Protocol):
    def get_job(self, job_id: str, connection=None) -> dict: ...
    def list_job_snapshots(self, since=None, **options) -> list[dict]: ...
    def history(self, job_id: str) -> dict: ...
    def read_capture_receipt(self, receipt_key: str, expected_fingerprint=None) -> dict | None: ...
    async def capture_external(self, payload: dict, **options) -> dict: ...


class DiscoveryStore(Protocol):
    def read_settings(self, connection=None) -> dict: ...
    def save_settings(self, changes: dict, **options) -> dict: ...
    def sources(self) -> dict: ...
    def source(self, source_id: str, **options) -> dict: ...
    def upsert_source(self, data: dict, **options) -> dict: ...
    def proposals(self) -> dict: ...
    def decide_proposal(self, candidate_id: str, decision: str, expected_revision=None) -> dict: ...
    def propose_source(self, url: str, evidence: dict) -> dict: ...
    def capture_item(self, item_id: str) -> dict: ...
    def claim_capture_import(self, item_id, generation, lifecycle_id, input_hash, provenance) -> str: ...
    def assert_capture_import_current(self, connection, item_id, generation, lifecycle_id, owner_token) -> None: ...
    def complete_capture_import(
        self, item_id, generation, lifecycle_id, input_hash, provenance, job_id, **options
    ) -> dict: ...
    def release_capture_import(self, item_id: str, token: str) -> None: ...
    def feedback(self, data: dict) -> dict: ...
    def feedback_sources(self, *, limit=100) -> list[dict]: ...
    def feedback_operation(self, operation_id: str, input_fingerprint: str, **options) -> dict | None: ...
    def save_feedback_proposals(self, proposals: list, **options) -> dict: ...
    def latest_target_plan(self) -> dict | None: ...
    def target_plan_operation(self, operation_id: str) -> dict | None: ...
    def save_target_plan(self, accepted: dict, assert_profile_current) -> dict: ...
    def run_request(self, run_id: str) -> dict | None: ...
    def claim_run(self, run_id: str, request: dict) -> dict: ...
    def heartbeat(self, lease: dict) -> None: ...
    def cancel(self, run_id: str) -> dict: ...
    def budget_remaining(self, lease: dict, limit: int) -> int: ...
    def unit(self, run_id: str, unit_id: str) -> dict | None: ...
    def source_result(self, lease: dict, source_id: str, status: str, **values) -> None: ...
    def runs(self) -> dict: ...
    def progress_summary(self, *, limit=100) -> dict: ...
    def finalize_bounded_units(self, lease: dict, limit: int) -> dict: ...
    def run_job_ids(self, run_id: str) -> dict: ...
    def settle(self, lease: dict, status: str, result=None, failure_code=None) -> str: ...
    def accept_posting(self, lease: dict, unit: dict, posting: dict, **options) -> dict: ...
