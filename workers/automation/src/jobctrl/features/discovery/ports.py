"""Application-owned ports at provider, canonical-owner and storage boundaries."""

from typing import Protocol

from jobctrl.features.discovery.query_fairness import BoardQueryTurn


class ExecutionPort(Protocol):
    def begin(self, lease: dict) -> None: ...
    def stop(self, lease: dict) -> None: ...
    async def run_board_unit(self, context, lease: dict, unit: dict, settings: dict, previous, turn: BoardQueryTurn | None = None) -> bool | None: ...


class ModelResult(Protocol):
    @property
    def value(self) -> dict: ...
    @property
    def provenance(self) -> dict: ...


class ModelPort(Protocol):
    def preflight_cost_accounting(self) -> None: ...
    def freeze_execution(self, model=None, **options): ...
    def fingerprint(self, **request) -> str: ...
    def receipts_for(self, operation: str, input_fingerprint: str, connection=None) -> list[dict]: ...
    def receipt(self, receipt_id: str, connection=None) -> dict: ...
    async def determine(
        self,
        *,
        operation: str,
        instructions: str,
        sources: list,
        response_schema: dict,
        context: dict | None = None,
        prompt_version: str = "1",
        lane: str = "interactive",
        model: str | None = None,
        execution=None,
        on_admitted=None,
    ) -> ModelResult: ...


class JobsPort(Protocol):
    def resolve_posting(self, data: dict, connection=None) -> dict | None: ...
    def get_job(self, job_id: str, connection=None) -> dict: ...
    def assert_posting_current(self, job_id: str, revision: int, source_hash=None, connection=None) -> dict: ...
    def list_job_snapshots(self, since=None, **options) -> list[dict]: ...
    def history(self, job_id: str) -> dict: ...
    def ingest(self, data: dict, **options) -> dict | None: ...
    def read_capture_receipt(self, receipt_key: str, expected_fingerprint=None) -> dict | None: ...
    async def capture_external(self, payload: dict, **options) -> dict: ...


class DiscoveryStore(Protocol):
    boards: tuple[str, ...]
    def read_settings(self, connection=None) -> dict: ...
    def save_settings(self, changes: dict, **options) -> dict: ...
    def sources(self) -> dict: ...
    def source(self, source_id: str, **options) -> dict: ...
    def set_board_state(self, source_id: str, state: str, expected: int) -> dict: ...
    def capture_item(self, item_id: str) -> dict: ...
    def claim_capture_import(self, item_id, generation, lifecycle_id, input_hash, provenance) -> str: ...
    def assert_capture_import_current(self, connection, item_id, generation, lifecycle_id, owner_token) -> None: ...
    def complete_capture_import(
        self, item_id, generation, lifecycle_id, input_hash, provenance, job_id, **options
    ) -> dict: ...
    def release_capture_import(self, item_id: str, token: str) -> None: ...
    def feedback(self, data: dict) -> dict: ...
    def feedback_sources(self, *, limit=100) -> list[dict]: ...
    def feedback_operation(self, operation_id: str, input_fingerprint: str, **options) -> dict | None: ...
    def save_feedback_proposals(self, proposals: list, **options) -> dict: ...
    def latest_target_plan(self) -> dict | None: ...
    def target_plan_operation(self, operation_id: str) -> dict | None: ...
    def save_target_plan(self, accepted: dict, assert_profile_current) -> dict: ...
    def cooldown(self, board: str, connection=None) -> float: ...
    def cooldown_deadline(self, board: str, connection=None) -> float: ...
    def linkedin_retry_state(self, run_id: str) -> dict: ...
    def finish_retry_peer_turn(self, lease: dict, yielded: str) -> None: ...
    def assessment_response(self, run_id: str, job_id: str, revision: int, response, delay: int | None) -> None: ...
    def reserve_board_request(self, lease: dict | None, board: str, interval: float, *,
                              unit_id=None, phase=None, receipt_key=None) -> dict: ...
    def finalize_action(self, run_id: str, status: str, code: str | None, connection) -> None: ...
    def unit_states(self, run_id: str) -> dict: ...
    def run_summary(self, run_id: str) -> dict: ...
    def posting_counts(self, run_id: str, connection=None) -> dict: ...
    def run_request(self, run_id: str) -> dict | None: ...
    def run_outcome(self, run_id: str) -> dict | None: ...
    def acquired_posting_revision(self, run_id: str, job_id: str, revision: int, source_id: str) -> bool: ...
    def claim_run(self, run_id: str, request: dict) -> dict: ...
    def continuation_request(self, payload: dict, connection=None) -> dict: ...
    def heartbeat(self, lease: dict) -> None: ...
    def cancel(self, run_id: str) -> dict: ...
    def budget_remaining(self, lease: dict, limit: int) -> int: ...
    def board_new_jobs_by_query(self, lease: dict) -> dict[str, int]: ...
    def unit(self, run_id: str, unit_id: str) -> dict | None: ...
    def record_board_failure(self, lease: dict, unit: dict, error, **options) -> dict: ...
    def source_result(self, lease: dict, source_id: str, status: str, **values) -> None: ...
    def runs(self) -> dict: ...
    def progress_summary(self, *, limit=100) -> dict: ...
    def finalize_bounded_units(self, lease: dict, limit: int) -> dict: ...
    def run_job_ids(self, run_id: str) -> dict: ...
    def observed_job(self, run_id: str, job_id: str) -> bool: ...
    def settled_intake(self, lease: dict, key: str, limit: int, cancelled, connection=None) -> dict | None: ...
    def role_call(self, owner: str, connection=None) -> dict | None: ...
    def bind_role_call(self, owner: str, expected: str, receipt_id: str, connection) -> None: ...
    def waiting_for_role_capacity(self, lease: dict, unit_id: str, reason: str) -> None: ...
    def role_review(self, binding: dict, *, decision=None, guard=None, connection=None) -> dict | None: ...
    def settle(self, lease: dict, status: str, result=None, failure_code=None) -> str: ...
    def accept_posting(self, lease: dict, unit: dict, posting: dict, **options) -> dict | None: ...
