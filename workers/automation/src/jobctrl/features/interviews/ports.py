"""Feature-owned application ports for Interview records and model receipts."""

from typing import Any, ContextManager, Protocol


class InterviewSession(Protocol):
    source_context: Any

    def next_generation(self, job_id: str) -> int: ...
    def generation_run(self, run_id: str) -> dict | None: ...
    def reserve_generation_run(self, run_id: str, job_id: str, input_hash: str, selection: dict) -> None: ...
    def preparation_for_run(self, job_id: str, run_id: str) -> tuple[dict, list] | None: ...
    def preparation(self, job_id: str, generation: int) -> tuple[dict, list] | None: ...
    def preparations(self, job_id: str, generation: int | None, limit: int, offset: int) -> tuple[int, list]: ...
    def latest_accepted(self, job_id: str) -> tuple[dict, list] | None: ...
    def save_preparation(self, value: dict, run_id: str, receipts: list) -> None: ...
    def save_determination(self, determination_id: str, envelope_json: str, receipt_id: str) -> None: ...
    def determination(self, identity: str) -> tuple[str, str] | None: ...
    def determination_bindings(self, receipt_ids: set[str]) -> list[dict]: ...
    def latest_note(self, job_id: str, question_id: str) -> dict | None: ...
    def notes(self, job_id: str, question_id: str | None, history: bool, limit: int, offset: int) -> tuple[int, list]: ...
    def save_note(self, value: dict) -> None: ...
    def delete_job_data(self, job_id: str) -> None: ...


class InterviewRepository(Protocol):
    def read_session(self, source_context: Any = None) -> ContextManager[InterviewSession]: ...
    def transaction(self, source_context: Any = None) -> ContextManager[InterviewSession]: ...


class ModelPort(Protocol):
    def receipt(self, receipt_id: str, connection: Any = None) -> dict: ...
    def selection(self, model: str | None = None) -> dict: ...
    def fingerprint(self, **kwargs) -> str: ...
    def receipts_for(self, operation: str, input_fingerprint: str, connection: Any = None) -> list[dict]: ...
    async def determine(self, **kwargs) -> Any: ...
