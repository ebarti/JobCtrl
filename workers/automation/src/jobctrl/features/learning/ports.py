"""Feature-owned persistence and model ports for Learning."""

from typing import Any, ContextManager, Protocol


class LearningSession(Protocol):
    source_context: Any

    def latest(self, kind: str, identity: str) -> dict | None: ...
    def list_latest(self, kind: str, limit: int) -> list[dict]: ...
    def history(self, milestone_id: str, limit: int) -> list[dict]: ...
    def latest_attempt(self, cohort_id: str) -> dict | None: ...
    def operation_for_receipt(self, receipt_id: str) -> str | None: ...
    def request(self, identity: str) -> dict | None: ...
    def reserve_request(self, identity: str, input_hash: str, action: str, cohort_id: str | None, at: str) -> None: ...
    def begin_model(self, identity: str, snapshot: dict, selection: dict, fingerprint: str, at: str) -> None: ...
    def bind_receipt(self, identity: str, receipt_id: str, fingerprint: str, at: str) -> bool: ...
    def finish_request(self, identity: str, response: dict, at: str) -> bool: ...
    def fail_request(self, identity: str, error: dict, at: str) -> None: ...
    def save_cohort(self, value: dict) -> None: ...
    def save_milestone(self, value: dict) -> None: ...
    def record_attempt(self, cohort_id: str, code: str | None, at: str, *, publish: bool) -> None: ...


class LearningRepository(Protocol):
    def read_session(self, session: LearningSession | None = None) -> ContextManager[LearningSession]: ...
    def transaction(self, session: LearningSession | None = None) -> ContextManager[LearningSession]: ...
    def request_lock(self, identity: str) -> ContextManager[None]: ...


class ModelPort(Protocol):
    def receipt(self, receipt_id: str, connection: Any = None) -> dict: ...
    def receipts_for(self, operation: str, input_fingerprint: str, connection: Any = None) -> list[dict]: ...
    def selection(self, model: str | None = None) -> dict: ...
    def fingerprint(self, **kwargs) -> str: ...
    async def determine(self, **kwargs) -> Any: ...
