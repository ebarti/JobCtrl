"""Fit's small public-feature and external-I/O contracts."""

from __future__ import annotations

from typing import Any, Callable, ContextManager, Protocol


class ProfileSnapshot(Protocol):
    profile_id: str
    profile_revision: int
    fact_semantics_version: int
    fingerprint: str

    def to_dict(self) -> dict: ...


class ScoringProfileSnapshot(ProfileSnapshot, Protocol):
    scoring_guidance: str


class ProfilePort(Protocol):
    def snapshot(self, profile_id="default", connection=None) -> ProfileSnapshot: ...
    def assert_current(self, snapshot, connection=None, *, facts_only=False) -> Any: ...
    async def request_authoring(self, brief: dict, *, cancelled=lambda: False) -> dict: ...
    def get_authoring_request(self, origin_key, profile_id="default", connection=None) -> dict | None: ...


class RequirementsPort(Protocol):
    def get_job_requirements(self, job_id: str, connection=None) -> dict: ...
    def get_requirement(self, requirement_id, revision=None, connection=None) -> dict: ...
    def assert_current(self, snapshot: dict, connection=None) -> None: ...
    def job_bindings(self, job_ids, connection=None, *, postings=None) -> dict: ...


class ModelResult(Protocol):
    value: dict
    provenance: dict


class ModelPort(Protocol):
    async def determine(self, *, operation: str, instructions: str, sources: list[dict] | dict,
                        response_schema: dict, context: dict | None = None, prompt_version: str = "1",
                        lane: str = "interactive", model: str | None = None) -> ModelResult: ...


class SettingsPort(Protocol):
    def snapshot(self, connection=None) -> dict: ...


class FitReadSession(Protocol):
    """A consistent Fit/public-source read view with no database handle."""

    def assessment(self, assessment_id: str) -> dict | None: ...
    def latest_assessment(self, profile_id, requirement_id, requirement_revision, *,
                          source_fingerprint=None) -> dict | None: ...
    def assessment_sources(self, assessment_id: str) -> list[dict]: ...
    def coverage(self, profile_id, requirement_id, requirement_revision, assessment_id, variant_id,
                 variant_revision) -> dict | None: ...
    def prior_coverage(self, profile_id, requirement_id, requirement_revision, variant_id,
                       variant_revision) -> list[dict]: ...
    def wording_requests(self, profile_id, requirement_id, requirement_revision) -> list[dict]: ...
    def latest_score(self, job_id: str) -> dict | None: ...
    def history(self, job_id: str) -> list[dict]: ...
    def anchors(self) -> list[dict]: ...
    def scored_job_ids(self) -> list[str]: ...
    def score_batch(self, job_ids) -> dict: ...
    def assessment_id_batch(self, bindings) -> dict: ...
    def coverage_rows(self, assessment_ids: list[str]) -> list[dict]: ...
    def operation(self, operation_id, input_fingerprint) -> dict | None: ...
    def profile_snapshot(self, profile_id="default") -> ScoringProfileSnapshot: ...
    def job_requirements(self, job_id: str) -> dict: ...
    def requirement(self, requirement_id, revision=None) -> dict: ...
    def authoring_request(self, origin_key, profile_id="default") -> dict | None: ...
    def settings_snapshot(self) -> dict: ...
    def requirement_bindings(self, job_ids, *, postings=None) -> dict: ...
    def validate_sources(self, profile_snapshot, requirements_snapshot, assessment=None, *, facts_only=True) -> None: ...


class FitStorePort(Protocol):
    """Domain-specific atomic Fit persistence and source authority boundary."""

    def read_snapshot(self, connection=None) -> ContextManager[FitReadSession]: ...
    def assessment(self, assessment_id: str, connection=None) -> dict | None: ...
    def latest_assessment(self, profile_id, requirement_id, requirement_revision, *, source_fingerprint=None,
                          connection=None) -> dict | None: ...
    def assessment_sources(self, assessment_id: str, connection=None) -> list[dict]: ...
    def coverage(self, profile_id, requirement_id, requirement_revision, assessment_id, variant_id,
                 variant_revision, connection=None) -> dict | None: ...
    def prior_coverage(self, profile_id, requirement_id, requirement_revision, variant_id,
                       variant_revision, connection=None) -> list[dict]: ...
    def wording_requests(self, profile_id, requirement_id, requirement_revision, connection=None) -> list[dict]: ...
    def latest_score(self, job_id: str, connection=None) -> dict | None: ...
    def history(self, job_id: str, connection=None) -> list[dict]: ...
    def anchors(self, connection=None) -> list[dict]: ...
    def scored_job_ids(self, connection=None) -> list[str]: ...
    def score_batch(self, job_ids, connection=None) -> dict: ...
    def assessment_id_batch(self, bindings, connection=None) -> dict: ...
    def coverage_rows(self, assessment_ids: list[str], connection=None) -> list[dict]: ...
    def operation(self, operation_id, input_fingerprint, connection=None) -> dict | None: ...
    def publish_assessment(self, record, facts, profile_snapshot, requirements_snapshot,
                           expected_assessment_id, *, cancelled: Callable[[], bool] = lambda: False) -> dict: ...
    def publish_score(self, candidate, profile_snapshot, requirements_snapshot, expected_revision, qualifications,
                      reuse_if_unchanged, operation_id, input_fingerprint, *,
                      cancelled: Callable[[], bool] = lambda: False) -> dict: ...
    def publish_score_correction(self, corrected, anchor, expected_revision, operation_id,
                                 input_fingerprint) -> dict: ...
    def publish_requirement_correction(self, record, facts, profile_snapshot, requirement_id,
                                       requirement_revision, expected_assessment_id) -> dict: ...
    def publish_coverage(self, relation, profile_snapshot, requirements_snapshot, assessment, *,
                         cancelled: Callable[[], bool] = lambda: False) -> None: ...
    def publish_wording_request(self, binding, profile_snapshot, requirements_snapshot, assessment, *,
                                cancelled: Callable[[], bool] = lambda: False) -> None: ...
    def complete_operation(self, operation_id, input_fingerprint, result) -> None: ...
    def delete_job_data(self, job_id, connection=None) -> None: ...
