"""Small I/O seams owned by Resumes."""

from __future__ import annotations

from typing import Callable, Protocol


class ResumeRepository(Protocol):
    def operation_result(self, operation: dict | None, *, connection=None) -> dict | None: ...
    def get(self, resume_id: str, *, connection=None) -> dict: ...
    def list(self, *, job_id: str | None = None, connection=None) -> list[dict]: ...
    def create(self, state: dict, *, fence: Callable, event: str, operation=None) -> dict: ...
    def change(self, resume_id: str, expected_version: int, mutate: Callable, *, event: str, operation=None) -> dict: ...
    def delete_job_data(self, job_id: str, connection=None) -> None: ...


class ProfilePort(Protocol):
    def snapshot(self, profile_id: str = "default", *, connection=None): ...


class FitPort(Protocol):
    def coverage_for(self, profile_revision, requirements, approved_variants, *, profile_id="default", connection=None): ...
    def assert_current(self, snapshot, connection=None): ...


class RequirementsPort(Protocol):
    def get_job_requirements(self, job_id: str, connection=None) -> dict: ...
    def assert_current(self, snapshot, connection=None): ...


class DeterminationResult(Protocol):
    value: dict
    provenance: dict


class SemanticPort(Protocol):
    async def determine(self, *, operation: str, instructions: str, sources: list[dict], response_schema: dict,
                        context: dict | None = None, prompt_version: str = "1", lane: str = "interactive",
                        model: str | None = None) -> DeterminationResult: ...
    def selection(self, model: str | None = None) -> dict: ...
    def fingerprint(self, **payload) -> str: ...
    def receipts_for(self, operation: str, input_fingerprint: str, connection=None) -> list[dict]: ...


class RendererPort(Protocol):
    def validate_theme(self, theme: dict) -> None: ...
    def html(self, document: dict, theme: dict, plate_document=None, template_layout=None) -> str: ...
    def render(self, document: dict, theme: dict, binding: dict) -> dict: ...
    def export(self, revision: dict, format: str) -> tuple[bytes, str, str]: ...
    def read_pdf(self, artifact: dict) -> bytes: ...
