"""Narrow semantic ports and immutable admissions used by Applications."""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from typing import Protocol


@dataclass(frozen=True)
class ExecutionClaim:
    run_id: str
    cancelled: Callable[[], bool]
    automatic: bool = False
    min_fit_override: int | None = None


@dataclass(frozen=True)
class SubmissionAdmission:
    result: dict | None = None
    payload: dict | None = None
    run: dict | None = None
    policy: dict | None = None
    attachment: bytes | None = None


@dataclass(frozen=True)
class RehearsalAdmission:
    result: dict | None = None
    payload: dict | None = None
    source_fence: Callable | None = None
    timeout_seconds: int | None = None


class ApplicationStore(Protocol):
    """Atomic feature commands; no raw SQL, connections or generic repository."""
    def prepare(self, job, command, tenant_id="local") -> dict: ...
    def review(self, job, command, tenant_id="local") -> dict: ...
    def control(self, job, command, tenant_id="local") -> dict: ...
    def admit_execution(self, claim: ExecutionClaim, command, tenant_id="local") -> SubmissionAdmission: ...
    def begin_rehearsal(self, job, payload_id, rehearsal_id, tenant_id="local") -> RehearsalAdmission: ...
    def complete_rehearsal(self, payload, evidence, tenant_id="local") -> dict: ...
    def retain_uncertain_submission(self, job, run_id, tenant_id="local") -> None: ...
    def settle_confirmation(self, run_id, payload, receipt, tenant_id="local") -> dict: ...
    def select_approved(self, command, tenant_id="local") -> list: ...
    def execution_policy(self) -> dict: ...
    def record_refusal(self, job, operation, code, tenant_id="local") -> None: ...
    def read(self, job, tenant_id="local") -> dict: ...
    def read_apply_review(self, tenant_id="local") -> dict: ...
    def summary(self, tenant_id="local", at=None) -> dict: ...
    def confirmed_anchors(self, tenant_id="local") -> list: ...
    def job_summaries(self, job_ids, connection=None, tenant_id="local") -> dict: ...
    def set_action_reader(self, reader) -> None: ...
    def list_outcomes(self, job_id=None, tenant_id="local") -> dict: ...
    def record_outcome(self, job_id, payload, tenant_id="local", connection=None) -> dict: ...
    def ensure_offer_milestone(self, job_id, connection=None, tenant_id="local") -> dict: ...
    def outreach_context(self, job_id, connection=None, tenant_id="local") -> dict: ...
    def delete_job_data(self, job_id, connection=None, tenant_id="local") -> None: ...


class BrowserInspection(Protocol):
    async def inspect(self, application_url: str) -> dict: ...


class InspectionModel(Protocol):
    async def classify(self, tenant, payload, details, source_fence) -> dict: ...
