"""Repeat-application-specific transaction capabilities."""

from collections.abc import Callable
from contextlib import AbstractContextManager
from typing import Any, Protocol


class RepeatSession(Protocol):
    def job_snapshot(self, job: str) -> dict: ...
    def confirmed_applications(self, tenant: str) -> list[dict]: ...
    def check(self, tenant: str, job: str, evidence_hash: str) -> dict | None: ...
    def determination(self, tenant: str, identifier: str) -> dict: ...
    def override(self, tenant: str, job: str, check_id: str, evidence_hash: str) -> dict | None: ...
    def repeated(self, tenant: str, key: str, request: dict) -> dict | None: ...
    def has_intent(self, tenant: str, job: str) -> bool: ...
    def append_check(self, tenant: str, job: str, evidence_hash: str, check: dict) -> None: ...
    def append_override(self, tenant: str, job: str, check_id: str, evidence_hash: str, identifier: str, reason: str, created_at: str) -> None: ...
    def consume_override(self, tenant: str, identifier: str, run_id: str, used_at: str) -> bool: ...
    def save_receipt(self, tenant: str, key: str, request: dict, response: dict) -> None: ...
    def emit(self, tenant: str, job: str, **references: Any) -> None: ...


class RepeatStore(Protocol):
    def read(self) -> AbstractContextManager[RepeatSession]: ...
    def write(self) -> AbstractContextManager[RepeatSession]: ...
    def model_fence(self, check: Callable[[RepeatSession], None]) -> Callable[..., None]: ...
    def set_handlers(self, reader: Callable[[RepeatSession, str, str], dict], guard: Callable[[RepeatSession, str, str, str | None], None]) -> None: ...
