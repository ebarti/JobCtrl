"""Screening-specific transaction capabilities, independent of persistence."""

from collections.abc import Callable
from contextlib import AbstractContextManager
from typing import Any, Protocol


class ScreeningSession(Protocol):
    def current(self, tenant: str, question: str) -> dict | None: ...
    def states(self, tenant: str, job: str) -> list[dict]: ...
    def history(self, tenant: str, job: str) -> list[dict]: ...
    def library(self, tenant: str) -> list[dict]: ...
    def library_entry(self, tenant: str, library_id: str | None) -> dict | None: ...
    def origin(self, tenant: str, question: str, revision: int) -> tuple[dict | None, bool]: ...
    def failures(self, tenant: str, job: str) -> list[dict]: ...
    def determination(self, tenant: str, identifier: str) -> dict: ...
    def source_snapshot(self, tenant: str, job: str, fact_ids: list[str], sensitive_ids: list[str]) -> tuple[dict, list[dict]]: ...
    def repeated(self, tenant: str, key: str, request: dict) -> dict | None: ...
    def append_state(self, tenant: str, job: str, state: dict, expected_revision: int) -> None: ...
    def append_library(self, tenant: str, entry: dict) -> None: ...
    def save_receipt(self, tenant: str, key: str, request: dict, response: dict) -> None: ...
    def emit(self, tenant: str, job: str, **references: Any) -> None: ...


class ScreeningStore(Protocol):
    def read(self) -> AbstractContextManager[ScreeningSession]: ...
    def write(self) -> AbstractContextManager[ScreeningSession]: ...
    def model_fence(self, check: Callable[[ScreeningSession], None]) -> Callable[..., None]: ...
    def set_payload_reader(self, reader: Callable[[ScreeningSession, str, str], list[dict]]) -> None: ...
    def record_failure(self, tenant: str, job: str, operation: str, code: str, question: str | None) -> None: ...
