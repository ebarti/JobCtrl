"""Application-owned I/O contracts for mail feedback and reviewed outcomes."""

from __future__ import annotations

from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Protocol


class FeedbackStore(Protocol):
    def read(self, connection=None) -> AbstractContextManager: ...
    def transaction(self, connection=None) -> AbstractContextManager: ...
    def outcome_anchors(self, tenant_id, kinds, connection=None) -> list[dict]: ...
    def known_message(self, message_id, tenant_id, connection=None) -> bool: ...
    def store_message(self, evidence: dict, suggestion: dict, connection) -> None: ...
    def outcome(self, outcome_id, tenant_id, connection=None) -> dict | None: ...
    def outcomes(self, tenant_id, job_id=None, *, connection=None) -> list[dict]: ...
    def suggestions(self, tenant_id, job_id=None, *, connection=None) -> list[dict]: ...
    def suggestion(self, suggestion_id, tenant_id, connection=None) -> dict | None: ...
    def evidence(self, evidence_id, tenant_id, connection=None) -> dict | None: ...
    def evidence_for_job(self, job_id, tenant_id, connection=None) -> list[dict]: ...
    def delete_job_data(self, job_id, tenant_id, connection=None) -> None: ...
    def store_outcome(self, value: dict, connection) -> None: ...
    def action_receipt(self, operation, job_id, request_id, tenant_id, connection=None) -> dict | None: ...
    def store_receipt(self, value: dict, connection) -> None: ...
    def confirmed_outcomes(self, tenant_id, job_id=None, *, connection=None) -> list[dict]: ...
    def decide_suggestion(self, suggestion_id, tenant_id, expected_version, changes: dict, connection) -> dict: ...
    def store_decision_fingerprint(self, suggestion_id, tenant_id, fingerprint, connection) -> None: ...
    def first_offer(self, job_id, tenant_id, connection=None) -> dict | None: ...
    def suggestion_counts(self, tenant_id, connection=None) -> dict: ...
    def append_event(self, connection, event_type, payload: dict, job_id) -> None: ...


class FeedbackJobs(Protocol):
    def get_posting_snapshot(self, job_id, connection=None) -> dict: ...


class FeedbackProfile(Protocol):
    def snapshot(self, *, tenant_id="local") -> Any: ...


class FeedbackModel(Protocol):
    async def determine(self, **request) -> Any: ...
    def receipt(self, receipt_id, connection=None) -> dict: ...
    def fingerprint(self, **request) -> str: ...


class FeedbackMail(Protocol):
    async def search_feedback_emails(self, *, to_email: str, after: datetime, before: datetime, max_results: int) -> list[dict]: ...
    async def read_email(self, *, message_id: str) -> dict: ...
