"""Narrow application ports for company history and its external boundaries."""

from __future__ import annotations

from collections.abc import AsyncIterator, Callable
from contextlib import AbstractAsyncContextManager, AbstractContextManager
from typing import Protocol


class CompanyUnitOfWork(Protocol):
    """One consistent company history, with cross-owner source and receipt guards."""

    def posting(self, job_id: str) -> dict: ...
    def assert_posting_current(self, job_id: str, revision: int, source_hash: str | None) -> dict: ...
    def receipt(self, receipt_id: str) -> dict: ...
    def configuration(self, company_id: str, revision: int | None = None) -> dict | None: ...
    def link(self, job_id: str) -> dict | None: ...
    def accepted(self, company_id: str) -> dict | None: ...
    def attempt(self, company_id: str) -> dict | None: ...
    def determination(self, company_id: str, fingerprint: str) -> dict | None: ...
    def recent_linked_jobs(self, limit: int) -> list[str]: ...
    def record_configuration(self, company_id: str, value: dict) -> None: ...
    def record_link(self, job_id: str, company_id: str, value: dict) -> None: ...
    def record_determination(self, fingerprint: str, company_id: str, receipt_id: str,
                             configuration_id: int, sources: list[dict], result: dict) -> None: ...
    def record_accepted(self, company_id: str, value: dict) -> None: ...
    def record_attempt(self, company_id: str, value: dict) -> None: ...
    def notify_linked_jobs(self, company_id: str) -> None: ...
    def delete_job_links(self, job_id: str) -> None: ...


class CompanyHistory(Protocol):
    def read(self) -> AbstractContextManager[CompanyUnitOfWork]: ...
    def write(self) -> AbstractContextManager[CompanyUnitOfWork]: ...


class ModelResult(Protocol):
    value: dict
    provenance: dict


class Model(Protocol):
    def selection(self, model: str | None = None) -> dict: ...
    def fingerprint(self, **kwargs) -> str: ...
    async def determine(self, **kwargs) -> ModelResult: ...


class PublicPage(Protocol):
    outcome: str
    status: int | None
    text: str
    final_url: str


class PublicPages(Protocol):
    def pages(self, urls: list[str], *, cancelled: Callable[[], bool]) -> AsyncIterator[tuple[str, PublicPage]]: ...


class RefreshLocks(Protocol):
    def hold(self, company_id: str, *, cancelled: Callable[[], bool]) -> AbstractAsyncContextManager[None]: ...
