"""Ports owned by the preparation application, independent of adapters."""

from __future__ import annotations

from collections.abc import Callable
from typing import Protocol

PreparationSettings = Callable[[], dict]
RunReader = Callable[[str], dict]


class PreparationCheckpoints(Protocol):
    def claim_job(self, run_id: str, job_id: str, owner_reclaimable: Callable[[str], bool]) -> None: ...
    def release_job(self, run_id: str, job_id: str) -> None: ...
    def open_run(self, run_id: str, request: dict, parent: str | None = None) -> None: ...
    def set_status(self, run_id: str, status: str) -> None: ...
    def step(self, run_id: str, job_id: str, stage: str) -> dict | None: ...
    def start_step(self, run_id: str, job_id: str, stage: str, inputs: dict) -> dict: ...
    def finish_step(self, run_id: str, job_id: str, stage: str, status: str,
                    *, result: dict | None = None, error_code: str | None = None) -> None: ...
    def get_run(self, run_id: str) -> dict: ...
    def list_runs(self, limit: int = 100) -> dict: ...
    def telemetry_runs(self, limit: int = 100) -> dict: ...
    def telemetry_run(self, run_id: str) -> dict: ...
    def job_summaries(self, job_ids: list[str], connection=None) -> dict: ...
    def request(self, run_id: str) -> dict | None: ...
    def targets(self, run_id: str) -> list[str] | None: ...
    def save_targets(self, run_id: str, ids: list[str]) -> list[str]: ...
    def inherit_retry_steps(self, run_id: str, parent: str, job_ids: list[str]) -> None: ...
