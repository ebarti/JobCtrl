"""Ports owned by the preparation application, independent of adapters."""

from __future__ import annotations

from collections.abc import Callable
from typing import Protocol

PreparationSettings = Callable[[], dict]


class RunReader(Protocol):
    def __call__(self, run_id: str, connection=None) -> dict: ...


class PreparationCheckpoints(Protocol):
    def add_handoff(self, payload: dict, action_run_id: str, connection) -> None: ...
    def owns_handoff(self, action_run_id: str, payload: dict) -> bool: ...
    def finish_handoff(self, run_id: str, status: str, error_code: str | None, connection) -> None: ...
    def failed_handoffs(self, run_id: str, connection) -> set[str]: ...
    def handoffs_pending(self, run_id: str) -> bool: ...
    def admit_run(self, run_id: str, request: dict, connection, *,
                  parent: str | None = None, targets: list[str] | None = None) -> None: ...
    def claim_job(self, run_id: str, job_id: str, owner_reclaimable: Callable[[str], bool]) -> None: ...
    def release_job(self, run_id: str, job_id: str) -> None: ...
    def open_run(self, run_id: str, request: dict, parent: str | None = None) -> None: ...
    def set_status(self, run_id: str, status: str) -> None: ...
    def finalize_run(self, run_id: str, status: str, error_code: str | None, connection) -> None: ...
    def settle_search(self, run_id: str, failed: bool, verify: Callable[..., bool]) -> bool: ...
    def step(self, run_id: str, job_id: str, stage: str, connection=None) -> dict | None: ...
    def start_step(self, run_id: str, job_id: str, stage: str, inputs: dict) -> dict: ...
    def record_capacity_wait(self, run_id: str, job_id: str, stage: str, reason: str) -> None: ...
    def prepare_step(self, run_id: str, job_id: str, stage: str, inputs: dict) -> None: ...
    def finish_step(self, run_id: str, job_id: str, stage: str, status: str,
                    *, result: dict | None = None, error_code: str | None = None, connection=None) -> None: ...
    def get_run(self, run_id: str, connection=None) -> dict: ...
    def list_runs(self, limit: int = 100) -> dict: ...
    def telemetry_runs(self, limit: int = 100) -> dict: ...
    def telemetry_run(self, run_id: str) -> dict: ...
    def job_summaries(self, job_ids: list[str], connection=None) -> dict: ...
    def request(self, run_id: str, connection=None) -> dict | None: ...
    def targets(self, run_id: str) -> list[str] | None: ...
    def save_targets(self, run_id: str, ids: list[str], *, route: str | None = None) -> tuple[list[str], str | None]: ...
    def inherit_retry_steps(self, run_id: str, parent: str, job_ids: list[str]) -> None: ...
