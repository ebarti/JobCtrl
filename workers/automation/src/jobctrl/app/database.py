# Advisory locks are local to the current PostgreSQL database. The shared write
# transaction fences cross-feature guard/read/write sequences and ensures that
# event IDs become visible in commit order. DBOS system tables have their own
# concurrency control and never need this lock to poll a queue.
_WRITE_LOCK = 0x4A435354


def _begin(engine, *, writable: bool) -> Connection:
    connection = None
    try:
        connection = Connection(engine.connect())
        if writable:
            connection.execute('SET TRANSACTION ISOLATION LEVEL READ COMMITTED READ WRITE')
        else:
            connection.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY')
        connection.execute('SET LOCAL search_path TO public')
        connection.execute("SET LOCAL TIME ZONE 'UTC'")
        if writable:
            connection.execute("SET LOCAL lock_timeout TO '30s'")
            connection.execute('SELECT pg_advisory_xact_lock(?)', (_WRITE_LOCK,))
        return connection
    except DBAPIError as exc:
        if connection is not None:
            connection.close()
        if getattr(exc.orig, 'sqlstate', None) == '55P03':
            raise AppError('database_busy', 'Another workspace transaction is still running.', 503) from None
        raise AppError('database_unavailable', 'The local PostgreSQL database is unavailable.', 503) from None


def _engine(url, *, read_only=False):
    arguments = {'client_encoding': 'utf8'}
    if read_only:
        arguments['options'] = '-c default_transaction_read_only=on'
    return create_engine(url, hide_parameters=True, connect_args=arguments, pool_pre_ping=True)


def _catalog(connection):
    try:
        cluster_id = connection.execute('SELECT system_identifier FROM pg_catalog.pg_control_system()').fetchone()[0]
    except DBAPIError:
        raise AppError('database_cluster_identity_unavailable', 'The local role must be able to read its PostgreSQL cluster identity.', 409) from None
    oid, encoding, collation, provider, manifest = connection.execute(
        "SELECT oid, pg_encoding_to_char(encoding), datcollate, datlocprovider, to_regclass('public.app_metadata') "
        'FROM pg_database WHERE datname=current_database()'
    ).fetchone()
    if encoding != 'UTF8':
        raise AppError('database_encoding', 'The workspace PostgreSQL database must use UTF-8.', 409)
    if provider != 'c' or collation not in {'C', 'POSIX', 'C.UTF-8', 'C.utf8'}:
        raise AppError('database_collation', 'The workspace database requires a C-locale PostgreSQL collation.', 409)
    if manifest is None:
        # Refuse existing third-party objects, including an orphan DBOS queue.
        occupied = connection.execute(
            "SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname NOT LIKE 'pg\\_%' "
            "AND nspname NOT IN ('public','information_schema')) OR "
            "EXISTS (SELECT 1 FROM pg_class WHERE relnamespace='public'::regnamespace) OR "
            "EXISTS (SELECT 1 FROM pg_proc WHERE pronamespace='public'::regnamespace) OR "
            "EXISTS (SELECT 1 FROM pg_type WHERE typnamespace='public'::regnamespace) OR "
            "EXISTS (SELECT 1 FROM pg_extension WHERE extname <> 'plpgsql')"
        ).fetchone()[0]
        if occupied:
            raise AppError('invalid_database_identity', 'The selected PostgreSQL database already contains unrelated objects.', 409)
        return cluster_id, oid, None
    try:
        metadata = dict(connection.execute('SELECT key,value FROM public.app_metadata'))
    except DBAPIError:
        raise AppError('invalid_database_identity', 'The selected database has incompatible workspace metadata.', 409) from None
    return cluster_id, oid, metadata


def _verify(workspace: Path, marker: Marker | None, metadata: dict | None) -> tuple[Marker, str]:
    if marker is None or metadata is None:
        raise AppError('workspace_changed', 'The PostgreSQL database and workspace identity must match.', 409)
    if metadata.get('schema_version') != str(SCHEMA_VERSION):
        raise AppError('unsupported_database_version', 'This database requires a compatible JobCtrl version.', 409)
    state = metadata.get('database_state')
    expected = {
        'application': 'jobctrl-python', 'schema_version': str(SCHEMA_VERSION), 'workspace_path': str(workspace),
        'workspace_id': marker['workspace_id'], 'database_id': marker['database_id'], 'database_state': state,
    }
    if expected != metadata or state not in {'staging', 'active'}:
        raise AppError('workspace_changed', 'The PostgreSQL database and workspace identity must match.', 409)
    return marker, state


def _instance_id(workspace, marker, database_oid):
    # Paired restores that replace the marker or the database invalidate stale
    # open editors. Restarts using the same pair keep their existing identity.
    if workspace.is_symlink():
        raise AppError('workspace_changed', 'The workspace directory changed. Restart JobCtrl.', 409)
    try:
        info = (workspace / MARKER).stat()
    except OSError:
        raise AppError('workspace_changed', 'The workspace database identity changed. Restart JobCtrl.', 409) from None
    return hashlib.sha256(f'{marker["database_id"]}:{database_oid}:{info.st_dev}:{info.st_ino}'.encode()).hexdigest()


def _require_state(state, staging):
    if state != ('staging' if staging else 'active'):
        if staging:
            raise AppError('database_already_active', 'The destination is already active.', 409)
        raise AppError('database_import_incomplete', 'The staged workspace import must finish before startup.', 409)


class Database:
    def _configure(self, workspace: Path | str, url, *, staging: bool, read_only: bool):
        self.workspace = workspace_path(workspace, create=not read_only)
        self.database_url = url.render_as_string(hide_password=False)
        self.libpq_url = url.set(drivername='postgresql').render_as_string(hide_password=False)
        self._staging = staging
        self.read_only = read_only
        self.engine = _engine(url, read_only=read_only)

    def __init__(self, workspace: Path | str, *, database_url: str | None = None, staging: bool = False):
        url = endpoint(database_url)
        self._configure(workspace, url, staging=staging, read_only=False)
        try:
            if not staging and has_source(self.workspace) and read_marker(self.workspace) is None:
                raise AppError('database_migration_required', 'Import the existing SQLite workspace before starting JobCtrl.', 409)
            with initialization_lock(self.workspace):
                marker = read_marker(self.workspace)
                with _begin(self.engine, writable=True) as connection:
                    cluster_id, oid, metadata = _catalog(connection)
                    if marker is not None:
                        verify_physical(marker, cluster_id, oid)
                    if metadata is None:
                        target = pending_target(url, oid, staging=staging)
                        if marker is not None and marker['pending_target'] != target:
                            raise AppError('workspace_changed', 'The workspace is already bound to another database.', 409)
                        if not staging and has_source(self.workspace):
                            raise AppError('database_migration_required', 'Import the existing SQLite workspace before starting JobCtrl.', 409)
                        if marker is None:
                            marker = Marker(workspace_id=str(uuid4()), database_id=str(uuid4()), pending_target=target,
                                            cluster_id=str(cluster_id), database_oid=oid)
                            write_marker(self.workspace, marker)
                        connection.execute(CORE_SCHEMA)
                        metadata = {
                            'application': 'jobctrl-python', 'schema_version': str(SCHEMA_VERSION),
                            'workspace_path': str(self.workspace), 'workspace_id': marker['workspace_id'],
                            'database_id': marker['database_id'], 'database_state': 'staging' if staging else 'active',
                        }
                        connection.executemany('INSERT INTO app_metadata (key,value) VALUES (?,?)', metadata.items())
                    marker, state = _verify(self.workspace, marker, metadata)
                    _require_state(state, staging)
                # PostgreSQL committed before publishing the final file. A crash
                # on either side can resume using the private pending marker.
                if marker['pending_target'] is not None:
                    marker['pending_target'] = None
                    write_marker(self.workspace, marker)
                self._marker = marker
                self.workspace_id = marker['workspace_id']
                self.instance_id = _instance_id(self.workspace, marker, oid)
        except BaseException:
            self.close()
            raise

    @classmethod
    def probe(cls, workspace: Path | str, *, database_url: str | None = None) -> dict | None:
        root = workspace_path(workspace, create=False)
        marker = read_marker(root)
        engine = _engine(endpoint(database_url))
        try:
            with _begin(engine, writable=False) as connection:
                cluster_id, oid, metadata = _catalog(connection)
                if marker is not None:
                    verify_physical(marker, cluster_id, oid)
                if marker is None and metadata is None:
                    return None
                if marker is not None and marker['pending_target'] is not None:
                    raise AppError('database_initialization_incomplete', 'Resume the interrupted workspace initialization.', 409)
                marker, state = _verify(root, marker, metadata)
                return {'state': state, 'workspaceId': marker['workspace_id'], 'databaseInstanceId': _instance_id(root, marker, oid)}
        finally:
            engine.dispose()

    @classmethod
    def open_existing(cls, workspace: Path | str, *, database_url: str | None = None) -> Database:
        database = cls.__new__(cls)
        database._configure(workspace, endpoint(database_url), staging=False, read_only=True)
        try:
            marker = read_marker(database.workspace)
            with _begin(database.engine, writable=False) as connection:
                cluster_id, oid, metadata = _catalog(connection)
                marker, state = _verify(database.workspace, marker, metadata)
                verify_physical(marker, cluster_id, oid)
                _require_state(state, staging=False)
                if marker['pending_target'] is not None:
                    raise AppError('database_initialization_incomplete', 'Resume the interrupted workspace initialization.', 409)
                database._marker = marker
                database.workspace_id = marker['workspace_id']
                database.instance_id = _instance_id(database.workspace, marker, oid)
            return database
        except BaseException:
            database.close()
            raise

    def _connection(self, *, writable) -> Connection:
        if writable and self.read_only:
            raise AppError('database_read_only', 'Workspace inspection requires a read-only transaction.', 409)
        connection = _begin(self.engine, writable=writable)
        try:
            marker = read_marker(self.workspace)
            if marker is None or marker != self._marker:
                raise AppError('workspace_changed', 'The workspace database changed. Restart JobCtrl.', 409)
            cluster_id, oid, metadata = _catalog(connection)
            verify_physical(marker, cluster_id, oid)
            marker, state = _verify(self.workspace, marker, metadata)
            if self.instance_id != _instance_id(self.workspace, marker, oid):
                raise AppError('workspace_changed', 'The workspace database changed. Restart JobCtrl.', 409)
            _require_state(state, self._staging)
            return connection
        except BaseException:
            connection.close()
            raise

    def connect(self) -> Connection:
        return self._connection(writable=False)

    @contextmanager
    def transaction(self) -> Iterator[Connection]:
        with self._connection(writable=True) as connection:
            yield connection

    def initialize_feature(self, name: str, schema: str) -> None:
        if not name or not name.replace('_', '').isalnum():
            raise ValueError('Invalid feature name')
        digest = hashlib.sha256(schema.encode()).hexdigest()
        with (self.connect() if self.read_only else self.transaction()) as connection:
            row = connection.execute('SELECT digest FROM app_feature_schemas WHERE name=?', (name,)).fetchone()
            if row:
                if row[0] != digest:
                    raise AppError('feature_schema_mismatch', f'Feature {name} requires an explicit schema upgrade.', 409)
                return
            if self.read_only:
                return
            connection.execute(schema)
            connection.execute('INSERT INTO app_feature_schemas VALUES (?,?)', (name, digest))

    def activate_import(self, connection: Connection) -> None:
        if not self._staging or connection.sa_connection.engine is not self.engine or not connection.in_transaction:
            raise RuntimeError('Activate an import only inside its staged database transaction.')
        updated = connection.execute(
            "UPDATE app_metadata SET value='active' WHERE key='database_state' AND value='staging'"
        ).rowcount
        if updated != 1:
            raise AppError('database_import_state', 'The staged database changed before activation.', 409)

    def close(self) -> None:
        self.engine.dispose()
